<article class="note">
  <h2>1. Classic Boba Milk Tea (Signature)</h2>
  <ul>
    <li><strong>Black Tea Base:</strong> 200ml brewed Assam Black Tea (75°C)</li>
    <li><strong>Sweetener & Milk:</strong> 25ml Brown Sugar syrup + 35g Non-dairy creamer</li>
    <li><strong>Assembly:</strong> Shake with ice for 10s. Add 1 scoop (50g) warm Tapioca Pearls.</li>
  </ul>
</article>

<article class="note">
  <h2>2. Taro Mochi Milk Tea</h2>
  <ul>
    <li><strong>Taro Base:</strong> 150ml Jasmine Green Tea + 40g Fresh Taro paste</li>
    <li><strong>Mochi Layer:</strong> Coat cup inner wall with 30g handmade Sweet Rice Mochi.</li>
    <li><strong>Assembly:</strong> Pour iced taro tea and top with boba pearls.</li>
  </ul>
</article>

<article class="note">
  <h2>3. Strawberry Cloud Tea</h2>
  <ul>
    <li><strong>Fruit Base:</strong> 4 fresh crushed strawberries + 180ml Green Tea</li>
    <li><strong>Cloud Topping:</strong> Layer 40ml salted cream cheese foam on top.</li>
  </ul>
</article>

<article class="note">
  <h2>4. Brown Sugar Pearl Fresh Milk</h2>
  <ul>
    <li><strong>Pearl Layer:</strong> Coat glass bottom with 60g warm Brown Sugar Pearls.</li>
    <li><strong>Milk Base:</strong> Fill cup with 220ml cold Hokkaido Fresh Milk.</li>
    <li><strong>Assembly:</strong> Top with milk foam and torch brown sugar crust.</li>
  </ul>
