<?php
require __DIR__ . '/config.php';
$u = current_user($db);
if (!$u) { header('Location: /login.php'); exit; }

$oid = (int)($_GET['order'] ?? 0);
$stmt = $db->prepare("SELECT * FROM orders WHERE id = ? AND member_id = ?");
$stmt->bind_param('ii', $oid, $u['id']);
$stmt->execute();
$order = $stmt->get_result()->fetch_assoc();
if (!$order) { header('Location: /orders.php'); exit; }

$msg = '';
// Slip upload — intern's "security": trust the Content-Type header + block a few scary extensions.
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_FILES['slip'])) {
    $f = $_FILES['slip'];
    $blocked = ['exe', 'sh', 'bat', 'com', 'dll']; // intentionally weak (misses .php and trusts Content-Type) for Zone 1 initial access
    $ext = strtolower(pathinfo($f['name'], PATHINFO_EXTENSION));
    $type = $f['type'] ?? '';
    if (in_array($ext, $blocked)) {
        $msg = "File type .$ext is not allowed!";
    } elseif (!str_starts_with($type, 'image/')) {
        $msg = "Only image slips are accepted (got '$type').";
    } elseif ($f['error'] !== UPLOAD_ERR_OK) {
        $msg = 'Upload failed, please try again.';
    } else {
        $dest = 'uploads/' . basename($f['name']);
        move_uploaded_file($f['tmp_name'], __DIR__ . '/' . $dest);
        $up = $db->prepare("UPDATE orders SET slip = ?, status = 'slip_sent' WHERE id = ?");
        $up->bind_param('si', $dest, $oid);
        $up->execute();
        $db->query("UPDATE members SET points = points + " . intdiv((int)$order['total'], 10) . " WHERE id = " . (int)$u['id']);
        $order['slip'] = $dest;
        $order['status'] = 'slip_sent';
        $msg = "Slip received (<a href='/$dest'>" . htmlspecialchars($f['name']) . "</a>) — verifying now!";
    }
}

$status_label = ['awaiting_slip' => 'Waiting for slip', 'slip_sent' => 'Verifying payment', 'paid' => 'Paid'];
page_top('Payment', 'orders');
?>
<h1>Pay for Order #<?= $oid ?></h1>
<div class="checkout">
  <div class="panel center">
    <h2>Scan to pay</h2>
    <div class="qr"><?php
      // cute fake-QR (decorative)
      echo "<svg viewBox='0 0 120 120' width='150'>";
      $cells = [[0,0,3],[8,0,3],[0,8,3],[8,8,3]];
      srand($oid);
      echo "<rect width='120' height='120' rx='10' fill='#fff'/>";
      for ($y=0;$y<12;$y++) for ($x=0;$x<12;$x++) if (rand(0,1)) echo "<rect x='".($x*10+2)."' y='".($y*10+2)."' width='7' height='7' rx='1.5' fill='#4A3B42'/>";
      echo "<circle cx='60' cy='60' r='14' fill='#FFC7D3'/><text x='60' y='65' font-size='12' text-anchor='middle'>🧋</text></svg>";
    ?></div>
    <p class="hint">PromptPay · Tang Wang Jeng ChaNom Co.</p>
    <p class="big-price">฿<?= (int)$order['total'] ?></p>
  </div>
  <div class="panel">
    <h2>Then send your slip</h2>
    <p class="status-pill"><?= $status_label[$order['status']] ?? $order['status'] ?></p>
    <?php if ($msg) echo "<p class='notice'>$msg</p>"; ?>
    <div class="notice" style="background: rgba(230, 244, 253, 0.4); border: 1px solid var(--sky-deep); color: var(--ink); margin-bottom: 12px; font-size: 0.82rem;">
      <strong>⚙️ Sandbox Mode:</strong> You can upload any local JPEG/PNG image to simulate payment. No real transfer is required.
    </div>
    <form method="post" enctype="multipart/form-data" class="stack">
      <div class="upload-zone">
        <label for="slip-file" class="upload-label">
          <span class="upload-icon">📷</span>
          <span class="upload-text">Select Bank Slip Image</span>
          <span class="upload-hint">Supports JPEG, PNG</span>
        </label>
        <input type="file" id="slip-file" name="slip" accept="image/*" required style="display: none;"
               onchange="document.querySelector('.upload-text').textContent = this.files[0] ? this.files[0].name : 'Select Bank Slip Image';">
      </div>
      <button class="btn" type="submit">Confirm Payment</button>
      <p class="hint">Please upload the confirmation slip generated by your mobile banking app after scanning the QR code.</p>
    </form>
  </div>
</div>
<?php page_bottom(); ?>
