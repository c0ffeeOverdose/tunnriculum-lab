// lab.rs — bridge to scripts/lab.sh (runs as the tunnriculum user via sudo -u lab)
use std::env;
use std::fs;
use std::process::{Command, Stdio};

use std::path::Path;

pub const LAB_SH: &str = "/home/lab/tunnriculum/train/scripts/lab.sh";
pub const PIN: &str = "1337";

fn lab_sh_path() -> &'static str {
    for p in [LAB_SH, "train/scripts/lab.sh", "scripts/lab.sh", "../scripts/lab.sh"] {
        if Path::new(p).exists() { return p; }
    }
    LAB_SH
}

fn env_file_path() -> &'static str {
    for p in [
        "/home/lab/tunnriculum/train/instances/tunnriculum.env",
        "train/instances/tunnriculum.env",
        "instances/tunnriculum.env",
        "../instances/tunnriculum.env",
    ] {
        if Path::new(p).exists() { return p; }
    }
    "/home/lab/tunnriculum/train/instances/tunnriculum.env"
}

fn is_tunnriculum() -> bool {
    if let Ok(user) = env::var("USER") {
        if user == "tunnriculum" { return true; }
    }
    if let Ok(out) = Command::new("id").arg("-un").output() {
        if let Ok(s) = String::from_utf8(out.stdout) {
            return s.trim() == "tunnriculum";
        }
    }
    false
}

pub fn run_lab_capture(args: &[String]) -> (i32, String) {
    let script = lab_sh_path();
    let mut cmd: Command;
    if is_tunnriculum() {
        cmd = Command::new("sudo");
        cmd.arg("-u").arg("lab").arg(LAB_SH);
    } else {
        cmd = Command::new(script);
    }
    for a in args { cmd.arg(a); }
    match cmd.output() {
        Ok(out) => {
            let code = out.status.code().unwrap_or(1);
            let mut s = String::new();
            s.push_str(&String::from_utf8_lossy(&out.stdout));
            if !out.stderr.is_empty() {
                if !s.is_empty() { s.push('\n'); }
                s.push_str(&String::from_utf8_lossy(&out.stderr));
            }
            if s.trim().is_empty() {
                s = if code == 0 { "(done)".to_string() } else { format!("(exit {})", code) };
            }
            (code, s)
        }
        Err(e) => (1, format!("failed to run {}: {}", script, e)),
    }
}

pub fn run_lab(args: &[String]) -> i32 {
    let (code, out) = run_lab_capture(args);
    println!("{}", out);
    code
}

    pub fn handle_action(action: &str, rest: &[String]) -> i32 {
    match action {
        "start" | "restart" => run_lab(&["up".to_string()]),
        "stop" | "reset" | "status" | "logs" | "smoke" | "kali" => run_lab(&[action.to_string()]),
        "ssh-kali" => ssh_kali(),
        "kali-key" => run_lab(&["kali-key".to_string()]),
        "peer" => {
            let endpoint = rest.get(0).map(|s| s.as_str()).unwrap_or("127.0.0.1");
            let valid = !endpoint.is_empty() && endpoint.chars().all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '-');
            if !valid { eprintln!("public host must be a hostname or IPv4 address"); return 1; }
            run_lab(&["peer".to_string(), endpoint.to_string()])
        }
        _ => { eprintln!("unknown action: {}", action); 1 }
    }
}

// SSH straight into the Kali box from labctl (menu 'SSH into Kali').
// Must be called while the TUI is suspended — it takes over the terminal.
pub fn ssh_kali() -> i32 {
    let env_path = env_file_path();
    let mut port = "2222".to_string();
    if let Ok(s) = fs::read_to_string(env_path) {
        for line in s.lines() {
            if let Some(v) = line.strip_prefix("KALI_SSH_PORT=") { port = v.to_string(); }
        }
    }
    // instance key generated by lab.sh init; read through the whitelisted lab.sh (works for both users)
    // run_lab_capture appends an extra newline when merging stderr — drop blank lines, keep the trailing newline
    // (the OpenSSH private key format requires the file to end with a newline)
    let key = {
        let raw = run_lab_capture(&["kali-key".to_string()]).1;
        let cleaned: Vec<&str> = raw.lines().filter(|l| !l.trim().is_empty()).collect();
        if cleaned.is_empty() { String::new() } else { cleaned.join("\n") + "\n" }
    };

    // per-user temp path: a fixed /tmp name breaks when lab and tunnriculum alternate
    let tmp_key = std::env::temp_dir().join(format!("labctl-kali-key-{}", std::process::id()));
    let use_key = !key.is_empty()
        && fs::write(&tmp_key, &key).is_ok()
        && fs::set_permissions(&tmp_key, std::os::unix::fs::PermissionsExt::from_mode(0o600)).is_ok();

    println!("\u{2500}\u{2500} SSH to Kali \u{2014} type 'exit' to come back \u{2500}\u{2500}");
    let status = if use_key {
        Command::new("ssh")
            .arg("-i").arg(&tmp_key)
            .arg("-o").arg("IdentitiesOnly=yes")
            .arg("-o").arg("StrictHostKeyChecking=no")
            .arg("-p").arg(&port)
            .arg("kali@127.0.0.1")
            .status()
    } else {
        // fallback: password auth (prompt on the real terminal)
        Command::new("ssh")
            .arg("-o").arg("StrictHostKeyChecking=no")
            .arg("-p").arg(&port)
            .arg("kali@127.0.0.1")
            .status()
    };
    let _ = fs::remove_file(&tmp_key);
    match status {
        Ok(s) => s.code().unwrap_or(1),
        Err(e) => { eprintln!("failed to run ssh: {}", e); 1 }
    }
}

pub fn read_flags() -> (String, String, String) {
    let env_path = env_file_path();
    let mut content = String::new();
    // direct read works for the lab user; the restricted tunnriculum user
    // (env is lab:0600) falls back to the whitelisted `lab.sh flags` via sudo
    match fs::read_to_string(env_path) {
        Ok(s) => content = s,
        Err(_) => {
            let (code, out) = run_lab_capture(&["flags".to_string()]);
            if code == 0 { content = out; }
        }
    }
    parse_flags(&content)
}

pub fn parse_flags(content: &str) -> (String, String, String) {
    let mut f1 = String::new();
    let mut f2 = String::new();
    let mut f3 = String::new();
    for line in content.lines() {
        if let Some(v) = line.strip_prefix("FLAG1=") { f1 = v.trim().to_string(); }
        if let Some(v) = line.strip_prefix("FLAG2=") { f2 = v.trim().to_string(); }
        if let Some(v) = line.strip_prefix("FLAG3=") { f3 = v.trim().to_string(); }
    }
    (f1, f2, f3)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_all_three_flags() {
        let (f1, f2, f3) = parse_flags("DB_PASS=x\nFLAG1=flag{a}\nFLAG2=flag{b}\nFLAG3=flag{c}\n");
        assert_eq!(f1, "flag{a}");
        assert_eq!(f2, "flag{b}");
        assert_eq!(f3, "flag{c}");
    }

    #[test]
    fn missing_file_yields_empty() {
        // "lab not initialized" case: no FLAG lines -> empty strings
        let (f1, f2, f3) = parse_flags("DB_PASS=x\n");
        assert!(f1.is_empty() && f2.is_empty() && f3.is_empty());
    }

    #[test]
    fn trims_trailing_whitespace() {
        let (f1, _, _) = parse_flags("FLAG1=flag{a}  \n");
        assert_eq!(f1, "flag{a}");
    }
}

// Non-blocking variant for streaming jobs: returns the spawned child with piped
// merged stdout+stderr. Caller polls via RunningJob.
pub fn spawn_lab(args: &[String]) -> std::io::Result<std::process::Child> {
    let mut cmd: Command;
    if is_tunnriculum() {
        cmd = Command::new("sudo");
        cmd.arg("-u").arg("lab").arg(LAB_SH);
    } else {
        cmd = Command::new(lab_sh_path());
    }
    for a in args { cmd.arg(a); }
    cmd.stdout(Stdio::piped()).stderr(Stdio::piped());
    cmd.spawn()
}
